# ============================================================================
# WHAT THIS FILE DOES:
#   Generates PDF reports from weekly report data.
#   Uses HTML → PDF conversion (the simplest approach).
#
# WHY A PLACEHOLDER:
#   PDF generation requires additional system dependencies (wkhtmltopdf
#   or WeasyPrint which needs Cairo). These are heavy to install in Docker.
#   The structure is here — you add the actual library when ready.
#
# PRODUCTION OPTIONS:
#   1. WeasyPrint (Python) — renders HTML/CSS to PDF, needs Cairo
#   2. wkhtmltopdf (CLI) — converts HTML to PDF via WebKit
#   3. Puppeteer/Playwright (headless Chrome) — most accurate rendering
#   4. ReportLab (Python) — programmatic PDF, no HTML needed
#   5. AWS Lambda with chrome-aws-lambda — serverless PDF generation
# ============================================================================

from app.shared.logging import get_logger

logger = get_logger(__name__)


class PdfGenerator:
    """
    PDF report generator.

    Currently returns HTML as a string (can be viewed in browser).
    When you install WeasyPrint, uncomment the generate_pdf method.
    """

    def generate_html_report(
        self,
        title: str,
        content: str,
        user_name: str,
    ) -> str:
        """
        Generate an HTML report that can be viewed in a browser or converted to PDF.

        This HTML is also used as the email body for weekly reports.
        """
        return f"""
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="utf-8">
            <title>{title}</title>
            <style>
                body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
                       max-width: 800px; margin: 40px auto; padding: 20px; color: #333; }}
                h1 {{ color: #3B82F6; border-bottom: 2px solid #3B82F6; padding-bottom: 8px; }}
                h2 {{ color: #1E40AF; margin-top: 24px; }}
                .meta {{ color: #666; font-size: 14px; }}
                .content {{ line-height: 1.6; }}
                .footer {{ margin-top: 40px; color: #999; font-size: 12px;
                          border-top: 1px solid #eee; padding-top: 16px; }}
            </style>
        </head>
        <body>
            <h1>🏥 {title}</h1>
            <p class="meta">Prepared for {user_name}</p>
            <div class="content">
                {content}
            </div>
            <div class="footer">
                Generated by Health Tracker AI
            </div>
        </body>
        </html>
        """

